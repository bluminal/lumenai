#!/usr/bin/env node

/**
 * Generate `plugins/synthex/evals/` case directories for `claude plugin eval`
 * (FR-HM34, Task 27) from the single manifest at tests/scripts/eval-cases.json.
 *
 * Each of the 18 manifest entries becomes one case directory:
 *
 *   plugins/synthex/evals/<id>/
 *     prompt.md            — directive that dispatches the target agent via
 *                             the Agent tool (allowed_tools: [Agent]) and
 *                             embeds the fixture content verbatim
 *     graders/
 *       00-agent-dispatch.md  — tool_used grader (Agent tool + namespaced
 *                                agent id), arm: with-only (ablation signal)
 *       01-verdict.md         — regex grader on the locked verdict header
 *       02-issue-<label>.md   — one regex grader per planted issue
 *
 * All graders are deterministic (`type: regex` / `type: tool_used`) per
 * FR-HM34: "No LLM or baseline grader gates CI." Ablation (`--ablation
 * with-without`, the CLI default whenever a plugin resolves) stays on for
 * reporting; the `arm: with-only` tag on the dispatch grader keeps it out of
 * the baseline (no-plugin) arm's score rather than failing that arm by
 * construction.
 *
 * Usage:
 *   node tests/scripts/generate-evals.mjs           # write/overwrite cases
 *   node tests/scripts/generate-evals.mjs --check   # exit 1 if stale
 *
 * Plan: docs/plans/harness-modernization.md, Phase 3 / Milestone 3.1 / Task 27.
 */

import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const GENERATED_MARKER =
  '<!-- Generated by tests/scripts/generate-evals.mjs from tests/scripts/eval-cases.json; do not edit by hand. -->';

const checkOnly = process.argv.includes('--check');
const scriptDir = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(scriptDir, '..', '..');
const manifestPath = join(repoRoot, 'tests', 'scripts', 'eval-cases.json');
const manifest = JSON.parse(readFileSync(manifestPath, 'utf-8'));
const evalsRoot = join(repoRoot, 'plugins', 'synthex', 'evals');

const FENCE_BY_TYPE = {
  diff: 'diff',
  json: 'json',
  text: 'text',
};

/**
 * Build the verdict-header regex for a case. Tolerant of the model
 * sometimes wrapping the verdict word in markdown bold (`**FAIL**`) — see
 * docs/testing.md "Task 16 (FR-HM6)" ("tolerating markdown bold around the
 * verdict word, which the model sometimes emits").
 */
function buildVerdictPattern(entry) {
  const heading = manifest.verdictHeadings[entry.agent];
  if (!heading) {
    throw new Error(`No verdictHeadings entry for agent "${entry.agent}"`);
  }
  const words = entry.expectedVerdictWords.join('|');
  return `## ${heading}: \\*{0,2}(?:${words})\\*{0,2}`;
}

function buildPromptBody(entry) {
  const fixturePath = join(repoRoot, entry.fixture);
  const fixtureContent = readFileSync(fixturePath, 'utf-8').replace(/\s+$/u, '');
  const fence = FENCE_BY_TYPE[entry.fixtureType] || 'text';
  const dispatchName = `synthex:${entry.agent}`;
  const extra = entry.extraContext
    ? `\n\nAdditional context: ${entry.extraContext}`
    : '';

  return [
    GENERATED_MARKER,
    '',
    `You MUST use the Agent tool to invoke the plugin agent named \`${dispatchName}\`.`,
    'Do NOT review or analyze the input yourself — dispatch it to that agent',
    'and let it produce the review. Pass the agent exactly the input below,',
    `unmodified, as its review target${extra ? ' (plus the additional context noted below)' : ''}.`,
    'After the agent responds, output its full response verbatim as your',
    'final answer, with no additional commentary before or after it.',
    '',
    `\`\`\`${fence}`,
    fixtureContent,
    '```',
    ...(extra ? [extra.trim()] : []),
    '',
  ].join('\n');
}

function buildPromptFrontmatter() {
  return ['---', 'allowed_tools: [Agent]', 'max_turns: 20', 'runs: 3', '---', ''].join('\n');
}

/**
 * Assemble a grader file: frontmatter fence FIRST (line 1 must be `---` —
 * an eval-harness requirement, so the generated-file marker cannot precede
 * it the way it does in prompt.md bodies), then the marker, then the
 * (optional) explanatory body. `frontmatterLines` are joined as-is (no
 * blank-line filtering, so a genuinely blank separator line is preserved);
 * pass only non-empty lines.
 */
function assembleGraderFile(frontmatterLines, bodyLines) {
  return [
    '---',
    ...frontmatterLines,
    '---',
    '',
    GENERATED_MARKER,
    '',
    ...bodyLines,
    '',
  ].join('\n');
}

function buildDispatchGrader(entry) {
  const dispatchName = `synthex:${entry.agent}`;
  const escaped = dispatchName.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return assembleGraderFile(
    [
      'type: tool_used',
      'tool: Agent',
      `input_match: '${escaped}'`,
      'min: 1',
      'weight: 1',
      'arm: with-only',
    ],
    [
      `Confirms the case actually dispatched the plugin's ${entry.agent} agent`,
      'via the Agent tool, rather than the top-level model reviewing the',
      'input itself. Excluded from the no-plugin baseline arm\'s score by',
      'design (arm: with-only) — that arm cannot dispatch a plugin agent, and',
      'the resulting delta is the ablation signal, reported but never gating.',
    ],
  );
}

function buildVerdictGrader(entry) {
  const pattern = buildVerdictPattern(entry);
  return assembleGraderFile(
    ['type: regex', `pattern: '${pattern}'`, 'target: last_message', 'weight: 1'],
    [
      `Locked verdict header must appear in the agent's final response:`,
      `\`${pattern}\`.`,
    ],
  );
}

function buildIssueGrader(entry, issue, index) {
  const frontmatterLines = ['type: regex', `pattern: '${issue.pattern}'`];
  if (issue.flags) frontmatterLines.push(`flags: ${issue.flags}`);
  frontmatterLines.push('target: last_message', 'weight: 1');

  return assembleGraderFile(frontmatterLines, [
    `Planted issue #${index + 1} ("${issue.label}") must be surfaced in the`,
    `agent's findings for ${entry.fixture}.`,
  ]);
}

function materializeCase(entry) {
  const caseDir = join(evalsRoot, entry.id);
  const gradersDir = join(caseDir, 'graders');
  const files = new Map();

  files.set(join(caseDir, 'prompt.md'), buildPromptFrontmatter() + buildPromptBody(entry));
  files.set(join(gradersDir, '00-agent-dispatch.md'), buildDispatchGrader(entry));
  files.set(join(gradersDir, '01-verdict.md'), buildVerdictGrader(entry));

  entry.plantedIssues.forEach((issue, index) => {
    const fileName = `02-issue-${String(index + 1).padStart(2, '0')}-${issue.label}.md`;
    files.set(join(gradersDir, fileName), buildIssueGrader(entry, issue, index));
  });

  return { caseDir, gradersDir, files };
}

function main() {
  const seenCaseDirs = new Set();
  let stale = false;

  for (const entry of manifest.cases) {
    const { caseDir, gradersDir, files } = materializeCase(entry);
    seenCaseDirs.add(caseDir);

    if (checkOnly) {
      for (const [path, content] of files) {
        const existing = existsSync(path) ? readFileSync(path, 'utf-8') : null;
        if (existing !== content) {
          console.error(`STALE: ${path.replace(repoRoot + '/', '')}`);
          stale = true;
        }
      }
      continue;
    }

    mkdirSync(gradersDir, { recursive: true });
    for (const [path, content] of files) {
      writeFileSync(path, content, 'utf-8');
    }
  }

  // Remove any previously generated case directory no longer in the
  // manifest. Never touch `results/` — that's `claude plugin eval`'s own
  // runtime output directory (gitignored), not a generated case.
  if (!checkOnly && existsSync(evalsRoot)) {
    for (const name of readdirSync(evalsRoot)) {
      if (name === 'results') continue;
      const dir = join(evalsRoot, name);
      if (!seenCaseDirs.has(dir)) {
        rmSync(dir, { recursive: true, force: true });
      }
    }
  }

  if (checkOnly && stale) {
    console.error(
      '\nplugins/synthex/evals/ is stale. Run: node tests/scripts/generate-evals.mjs',
    );
    process.exit(1);
  }

  if (!checkOnly) {
    console.log(`Generated ${manifest.cases.length} eval cases under ${evalsRoot}`);
  }
}

main();
