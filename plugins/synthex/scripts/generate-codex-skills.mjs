// FR-HM9: one shared agentskills.io `compatibility` sentence for every
// command wrapper. None of the generated wrappers execute scripts
// themselves (they only point at the canonical file to read), so a single
// sentence describing the minimal host requirement covers all 18.
export const COMMAND_COMPATIBILITY = 'Requires a shell tool; node or jq optional';

// FR-HM10: Codex reads `agents/openai.yaml` next to each agent wrapper's
// SKILL.md (see https://learn.chatgpt.com/docs/build-skills). Setting
// `policy.allow_implicit_invocation: false` keeps agent wrappers off
// Codex's implicit-invocation / catalog-budget path entirely, matching the
// Grok-honored `user-invocable: false` frontmatter field on the same
// wrapper's SKILL.md.
export const AGENT_OPENAI_YAML =
  '# Generated by scripts/generate-codex-skills.mjs; do not edit.\npolicy:\n  allow_implicit_invocation: false\n';

/**
 * Strips a leading YAML frontmatter block from a canonical command or agent
 * definition, returning only the Markdown body.
 *
 * The block is delimited by an opening `---` line and the first subsequent
 * line that is *exactly* `---` (no leading/trailing characters). Frontmatter
 * is never scanned for the H1 (see `extractTitle`): once Task 28 adds
 * `description:` fields, a multi-line block-scalar value could contain a
 * line that starts with `#` (or, if indentation is dropped, a bare `---`);
 * confining the title search to the body sidesteps that entirely rather
 * than relying on the frontmatter's own text never colliding with either
 * marker.
 *
 * @param {string} source
 * @returns {string} the Markdown body, or the original source unchanged if
 *   it does not open with a well-formed frontmatter fence.
 */
export function stripFrontmatter(source) {
  if (!source.startsWith(`${FRONTMATTER_FENCE}\n`)) return source;

  const lines = source.split('\n');
  for (let i = 1; i < lines.length; i += 1) {
    if (lines[i] === FRONTMATTER_FENCE) {
      return lines.slice(i + 1).join('\n');
    }
  }

  // No closing fence found; nothing to safely strip, so fall back to the
  // whole file rather than guessing where the body starts.
  return source;
}

/**
 * Extracts the first Markdown H1 (`# Title`) from a canonical command or
 * agent definition, ignoring any leading YAML frontmatter block.
 *
 * @param {string} source
 * @returns {string | undefined}
 */
export function extractTitle(source) {
  return stripFrontmatter(source).match(/^#\s+(.+)$/m)?.[1]?.trim();
}

function sourceEntries(kind) {
  const entries = claudeManifest[`${kind}s`];
  if (!Array.isArray(entries)) {
    throw new Error(`Claude manifest field "${kind}s" must be an array`);
  }

  return entries.map((manifestPath) => {
    if (typeof manifestPath !== 'string' || !manifestPath.endsWith('.md')) {
      throw new Error(`Invalid ${kind} path in Claude manifest: ${manifestPath}`);
    }

    const sourcePath = resolve(pluginRoot, manifestPath);
    if (!existsSync(sourcePath)) {
      throw new Error(`Missing canonical ${kind} definition: ${manifestPath}`);
    }

    const slug = basename(manifestPath, '.md');
    const source = readFileSync(sourcePath, 'utf8');
    const title = extractTitle(source);
    if (!title) {
      throw new Error(`Canonical ${kind} definition has no H1: ${manifestPath}`);
    }

    return { kind, manifestPath, slug, title };
  });
}

/**
 * Looks up a command wrapper's generator-side description and argument
 * hint. Commands never source a description from their own frontmatter
 * (OQ-2: spikes.md Task 6) so this table is the only place a command
 * wrapper's description lives.
 *
 * @param {string} slug
 */
function commandDescription(slug) {
  const entry = COMMAND_DESCRIPTIONS[slug];
  if (!entry) {
    throw new Error(`Missing COMMAND_DESCRIPTIONS entry for command: ${slug}`);
  }
  return entry;
}

/**
 * Looks up an agent wrapper's description. This is the one function Task
 * 28 repoints at the agent's own frontmatter `description:` field once
 * PR-A lands; every other reference to an agent wrapper's description goes
 * through this function so that change has a single call site.
 *
 * @param {string} slug
 */
function agentDescription(slug) {
  const description = AGENT_DESCRIPTIONS[slug];
  if (!description) {
    throw new Error(`Missing AGENT_DESCRIPTIONS entry for agent: ${slug}`);
  }
  return description;
}

// FR-HM12 (Task 20): rendered once from the single-sourced host-matrix.mjs
// table. The table itself is generated into the single shared
// `docs/tool-map.md` (see `TOOL_MAP_DOCS_RELATIVE_PATH` below) rather than
// embedded in each of the 46 wrappers: embedding the ~900-byte table
// directly in every wrapper was tried first (the FR-HM12 "compact table"
// default) but pushed the combined size of all wrappers past a hard
// truncation limit in `opencode debug skill`'s piped stdout (observed
// truncating full JSON output around ~146 KB; see
// docs/specs/harness-modernization/spikes.md and the Task 20 commit for the
// reproduction), breaking OpenCode's activation compat profile. Every
// wrapper's step 4 instead points at the shared file (the D17 read
// pattern); the two FR-HM12 rules and the Hermes footnote stay inline
// because they are cheap (a few hundred bytes total) and the acceptance
// criteria requires them present verbatim in every wrapper.
const TOOL_MAP_TABLE = renderToolMapTable();
const TOOL_MAP_DOCS_RELATIVE_PATH = 'docs/tool-map.md';
const TOOL_MAP_DOCS_PATH = join(pluginRoot, 'docs', 'tool-map.md');

function toolMapDocContents() {
  return `${GENERATED_MARKER}

# Synthex host tool-name map (FR-HM12)

Every non-Claude wrapper's step 4 reads this file. It maps Claude Code's native tool names to the closest tool on each of the five other harnesses Synthex targets, verbatim from the FR-HM12 table in \`docs/reqs/harness-modernization.md\`, single-sourced from \`scripts/lib/host-matrix.mjs\`.

${TOOL_MAP_TABLE}

${HERMES_READ_FILE_NOTE}
`;
}

function skillContents(entry) {
  const skillDir = join(skillsRoot, entry.slug);
  const sourcePath = resolve(pluginRoot, entry.manifestPath);
  const canonicalPath = relative(skillDir, sourcePath).split(sep).join('/');
  const toolMapPath = relative(skillDir, TOOL_MAP_DOCS_PATH).split(sep).join('/');
  const isCommand = entry.kind === 'command';
  const description = isCommand
    ? commandDescription(entry.slug).description
    : agentDescription(entry.slug);
  const invocationRule = isCommand
    ? "Execute the requested workflow. When it names a Synthex agent, delegate with the host harness's subagent mechanism when the source calls for delegation, and tell that subagent to read the matching file under `agents/` completely before acting."
    : 'Adopt the identity, responsibilities, review criteria, behavioral rules, and output contract in the source. If you are running as a delegated subagent, return the requested result to the caller.';

  const frontmatterLines = [`name: ${entry.slug}`, `description: ${JSON.stringify(description)}`];
  if (isCommand) {
    const { argumentHint } = commandDescription(entry.slug);
    frontmatterLines.push(
      `argument-hint: ${JSON.stringify(argumentHint)}`,
      `compatibility: ${JSON.stringify(COMMAND_COMPATIBILITY)}`,
      'metadata:',
      `  short-description: ${JSON.stringify(description)}`,
    );
  } else {
    frontmatterLines.push('user-invocable: false');
  }

  return `---
${frontmatterLines.join('\n')}
---

${GENERATED_MARKER}

# Synthex ${entry.title}

This is the shared Agent Skills entrypoint for the canonical Synthex ${entry.kind} definition. Codex, Gemini CLI, OpenCode, Grok, and Hermes load this file.

1. Read [\`${entry.manifestPath}\`](${canonicalPath}) completely before acting.
2. Treat that file, not this wrapper, as the behavioral source of truth. Resolve its relative paths from the canonical file's directory, and resolve repository-style paths beginning with \`plugins/synthex/\` from this installed plugin root.
3. ${invocationRule}
4. Translate Claude Code-specific tool names to the closest tools in the current host, per the table in [\`${TOOL_MAP_DOCS_RELATIVE_PATH}\`](${toolMapPath}), while preserving the workflow's intent and safety constraints. ${HERMES_READ_FILE_NOTE}
5. ${RULE_SKIP_UNAVAILABLE_TOOL}
6. ${RULE_ADOPT_INLINE}
7. Keep provider-specific behavior only where the canonical workflow genuinely targets that provider. Do not edit the canonical definition merely to adapt it at runtime.
`;
}

function main() {
  const entries = [...sourceEntries('command'), ...sourceEntries('agent')];
  const expectedSlugs = new Set(entries.map(({ slug }) => slug));
  if (expectedSlugs.size !== entries.length) {
    throw new Error('Claude command and agent names must be unique for Codex skills');
  }

  const mismatches = [];

  // FR-HM12 (Task 20): the shared tool-map doc every wrapper's step 4 reads,
  // generated once here from the same `host-matrix.mjs` source as the
  // per-wrapper `TOOL_MAP_TABLE` constant.
  const expectedToolMapDoc = toolMapDocContents();
  if (checkOnly) {
    if (!existsSync(TOOL_MAP_DOCS_PATH) || readFileSync(TOOL_MAP_DOCS_PATH, 'utf8') !== expectedToolMapDoc) {
      mismatches.push(relative(pluginRoot, TOOL_MAP_DOCS_PATH));
    }
  } else {
    mkdirSync(dirname(TOOL_MAP_DOCS_PATH), { recursive: true });
    writeFileSync(TOOL_MAP_DOCS_PATH, expectedToolMapDoc);
  }

  for (const entry of entries) {
    const skillDir = join(skillsRoot, entry.slug);
    const skillPath = join(skillDir, 'SKILL.md');
    const expected = skillContents(entry);

    if (checkOnly) {
      if (!existsSync(skillPath) || readFileSync(skillPath, 'utf8') !== expected) {
        mismatches.push(relative(pluginRoot, skillPath));
      }
    } else {
      mkdirSync(skillDir, { recursive: true });
      writeFileSync(skillPath, expected);
    }

    // FR-HM10: agent wrappers carry a sibling `agents/openai.yaml` (Codex
    // reads it) that turns off implicit invocation, alongside the
    // `user-invocable: false` frontmatter field on SKILL.md itself.
    if (entry.kind === 'agent') {
      const openaiYamlDir = join(skillDir, 'agents');
      const openaiYamlPath = join(openaiYamlDir, 'openai.yaml');

      if (checkOnly) {
        if (!existsSync(openaiYamlPath) || readFileSync(openaiYamlPath, 'utf8') !== AGENT_OPENAI_YAML) {
          mismatches.push(relative(pluginRoot, openaiYamlPath));
        }
      } else {
        mkdirSync(openaiYamlDir, { recursive: true });
        writeFileSync(openaiYamlPath, AGENT_OPENAI_YAML);
      }
    }
  }

  if (existsSync(skillsRoot)) {
    for (const directory of readdirSync(skillsRoot, { withFileTypes: true })) {
      if (!directory.isDirectory() || expectedSlugs.has(directory.name)) continue;

      const skillPath = join(skillsRoot, directory.name, 'SKILL.md');
      if (
        existsSync(skillPath) &&
        readFileSync(skillPath, 'utf8').includes(GENERATED_MARKER)
      ) {
        if (checkOnly) {
          mismatches.push(relative(pluginRoot, skillPath));
        } else {
          rmSync(join(skillsRoot, directory.name), { recursive: true, force: true });
        }
      }
    }
  }

  if (mismatches.length > 0) {
    console.error('Agent Skills wrappers are out of date:');
    for (const mismatch of mismatches.sort()) console.error(`- ${mismatch}`);
    console.error('Run: node plugins/synthex/scripts/generate-codex-skills.mjs');
    process.exitCode = 1;
  } else {
    console.log(
      checkOnly
        ? `Agent Skills wrappers are current (${entries.length}).`
        : `Generated ${entries.length} Agent Skills wrappers.`
    );
  }
}

// Only run the generator when this file is executed directly (`node
// generate-codex-skills.mjs [--check]`). Tests import `extractTitle` /
// `stripFrontmatter` from this module for unit coverage; importing must
// never write or check wrapper files as a side effect.
const isMainModule =
  process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMainModule) {
  main();
}
